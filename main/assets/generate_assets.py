from pathlib import Path
from typing import Any, Iterable, Optional


HEADER_MARKER = "/* Generated by assets/generate_assets.py. Do not edit. */"
IMAGE_MARKER = "/* Generated image: assets/generate_assets.py. Do not edit. */"
FONT_MARKER = "/* Generated font: assets/generate_assets.py. Do not edit. */"
CMAKE_MARKER = "# Generated by assets/generate_assets.py. Do not edit."

IMAGE_EXTENSIONS = {".jpeg", ".jpg", ".png", ".svg"}
FONT_EXTENSIONS = {".otf", ".ttf", ".woff", ".woff2"}
LVGL_COLOR_FORMATS = {
    "A1",
    "A2",
    "A4",
    "A8",
    "AL88",
    "ARGB8565",
    "ARGB8888",
    "I1",
    "I2",
    "I4",
    "I8",
    "L8",
    "RGB565",
    "RGB565A8",
    "RGB565_SWAPPED",
    "RGB888",
    "XRGB8888",
}
GFX_FORMATS = {"GFX_RGB565_SWAPPED"}
IMAGE_FORMATS = {f"LVGL_{item}" for item in LVGL_COLOR_FORMATS} | GFX_FORMATS
LVGL_ALPHA_FORMATS = {
    "LVGL_A1",
    "LVGL_A2",
    "LVGL_A4",
    "LVGL_A8",
    "LVGL_AL88",
    "LVGL_ARGB8565",
    "LVGL_ARGB8888",
    "LVGL_RGB565A8",
}
GENERATED_MARKERS = {IMAGE_MARKER, FONT_MARKER}


class AssetError(RuntimeError):
    pass


@dataclass(frozen=True)
class ImageAsset:
    source: Path
    source_name: str
    symbol: str
    format: str
    width: Optional[int]
    height: Optional[int]
    stride_align: int


@dataclass(frozen=True)
class FontAsset:
    source: Path
    source_name: str
    symbol: str
    size: int
    bpp: int
    ranges: tuple[str, ...]
    symbols: str
    args: tuple[str, ...]


@dataclass(frozen=True)
class AssetManifest:
    root: Path
    images: tuple[ImageAsset, ...]
    fonts: tuple[FontAsset, ...]


def _expect_object(value: Any, label: str) -> dict[str, Any]:
    if not isinstance(value, dict):
        raise AssetError(f"{label} must be an object")
    return value


def _expect_list(value: Any, label: str) -> list[Any]:
    if not isinstance(value, list):
        raise AssetError(f"{label} must be an array")
    return value


def _reject_unknown_keys(value: dict[str, Any], allowed: set[str], label: str) -> None:
    unknown = sorted(set(value) - allowed)
    if unknown:
        raise AssetError(f"{label} has unknown field(s): {', '.join(unknown)}")


def _required_string(value: dict[str, Any], key: str, label: str) -> str:
    result = value.get(key)
    if not isinstance(result, str) or not result.strip():
        raise AssetError(f"{label}.{key} must be a non-empty string")
    return result.strip()


def _optional_positive_int(value: dict[str, Any], key: str, label: str) -> Optional[int]:
    result = value.get(key)
    if result is None:
        return None
    if isinstance(result, bool) or not isinstance(result, int) or result <= 0:
        raise AssetError(f"{label}.{key} must be a positive integer")
    return result


def _positive_int(value: dict[str, Any], key: str, label: str, default: Optional[int] = None) -> int:
    result = value.get(key, default)
    if isinstance(result, bool) or not isinstance(result, int) or result <= 0:
        raise AssetError(f"{label}.{key} must be a positive integer")
    return result


def _source_path(root: Path, source_name: str, expected_dir: str, label: str) -> tuple[Path, str]:
    relative = Path(source_name)
    if relative.is_absolute():
        raise AssetError(f"{label}.source must be relative to the assets directory")

    root = root.resolve()
    source = (root / relative).resolve()
    try:
        normalized = source.relative_to(root)
    except ValueError as exc:
        raise AssetError(f"{label}.source escapes the assets directory: {source_name}") from exc

    if not normalized.parts or normalized.parts[0] != expected_dir:
        raise AssetError(f"{label}.source must be under {expected_dir}/")
    if not source.is_file():
        raise AssetError(f"{label}.source does not exist: {normalized.as_posix()}")
    return source, normalized.as_posix()


def _sanitize_symbol(value: str) -> str:
    symbol = re.sub(r"[^0-9A-Za-z_]", "_", value)
    symbol = re.sub(r"_+", "_", symbol).strip("_").lower()
    if not symbol:
        symbol = "asset"
    if symbol[0].isdigit():
        symbol = f"asset_{symbol}"
    return symbol


def _derived_symbol(source_name: str, prefix: str, suffix: str = "") -> str:
    relative = Path(source_name).with_suffix("")
    parts = relative.parts[1:] if len(relative.parts) > 1 else relative.parts
    body = _sanitize_symbol("_".join(parts))
    if suffix:
        normalized_suffix = re.sub(r"[^0-9A-Za-z_]", "_", suffix)
        normalized_suffix = re.sub(r"_+", "_", normalized_suffix).strip("_").lower()
        body = f"{body}_{normalized_suffix}"
    return f"{prefix}_{body}"


def _symbol(value: dict[str, Any], source_name: str, prefix: str, label: str, suffix: str = "") -> str:
    symbol = value.get("symbol")
    if symbol is None:
        return _derived_symbol(source_name, prefix, suffix)
    if not isinstance(symbol, str) or not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", symbol):
        raise AssetError(f"{label}.symbol must be a C identifier")
    if not symbol.startswith(f"{prefix}_"):
        raise AssetError(f"{label}.symbol must start with {prefix}_")
    return symbol


def _parse_image(root: Path, raw: Any, index: int) -> ImageAsset:
    label = f"images[{index}]"
    value = _expect_object(raw, label)
    _reject_unknown_keys(
        value,
        {"format", "height", "source", "stride_align", "symbol", "width"},
        label,
    )

    source, source_name = _source_path(root, _required_string(value, "source", label), "images", label)
    extension = source.suffix.lower()
    if extension not in IMAGE_EXTENSIONS:
        raise AssetError(f"{label}.source has unsupported extension: {extension}")

    width = _optional_positive_int(value, "width", label)
    height = _optional_positive_int(value, "height", label)
    if (width is None) != (height is None):
        raise AssetError(f"{label}.width and {label}.height must be provided together")
    if extension == ".svg" and (width is None or height is None):
        raise AssetError(f"{label} must set width and height for deterministic SVG rendering")

    if extension == ".svg":
        default_format = "LVGL_A8"
    elif extension in {".jpg", ".jpeg"}:
        default_format = "LVGL_RGB565"
    else:
        default_format = "LVGL_RGB565A8"
    image_format = value.get("format", default_format)
    if not isinstance(image_format, str):
        raise AssetError(f"{label}.format must be a string")
    image_format = image_format.upper()
    if image_format not in IMAGE_FORMATS:
        raise AssetError(f"{label}.format is not supported: {image_format}")

    stride_align = _positive_int(value, "stride_align", label, 1)
    if stride_align not in {1, 2, 4, 8, 16}:
        raise AssetError(f"{label}.stride_align must be one of 1, 2, 4, 8, or 16")

    return ImageAsset(
        source=source,
        source_name=source_name,
        symbol=_symbol(value, source_name, "image", label),
        format=image_format,
        width=width,
        height=height,
        stride_align=stride_align,
    )


def _string_list(value: dict[str, Any], key: str, label: str) -> tuple[str, ...]:
    raw = value.get(key, [])
    items = _expect_list(raw, f"{label}.{key}")
    result = []
    for index, item in enumerate(items):
        if not isinstance(item, str) or not item:
            raise AssetError(f"{label}.{key}[{index}] must be a non-empty string")
        result.append(item)
    return tuple(result)


def _parse_font(root: Path, raw: Any, index: int) -> FontAsset:
    label = f"fonts[{index}]"
    value = _expect_object(raw, label)
    _reject_unknown_keys(value, {"args", "bpp", "ranges", "size", "source", "symbol", "symbols"}, label)

    source, source_name = _source_path(root, _required_string(value, "source", label), "fonts", label)
    extension = source.suffix.lower()
    if extension not in FONT_EXTENSIONS:
        raise AssetError(f"{label}.source has unsupported extension: {extension}")

    size = _positive_int(value, "size", label)
    bpp = _positive_int(value, "bpp", label, 4)
    if bpp not in {1, 2, 4, 8}:
        raise AssetError(f"{label}.bpp must be one of 1, 2, 4, or 8")

    ranges = _string_list(value, "ranges", label)
    symbols = value.get("symbols", "")
    if not isinstance(symbols, str):
        raise AssetError(f"{label}.symbols must be a string")
    if not ranges and not symbols:
        raise AssetError(f"{label} must define ranges and/or symbols")

    args = _string_list(value, "args", label)
    reserved_args = {"--bpp", "--font", "--format", "--output", "--size", "--symbols", "-o", "-r"}
    has_reserved_arg = any(
        argument in reserved_args
        or any(argument.startswith(f"{option}=") for option in reserved_args)
        or argument.startswith(("-o", "-r"))
        for argument in args
    )
    if has_reserved_arg:
        raise AssetError(
            f"{label}.args cannot override size, bpp, ranges, symbols, font, format, or output"
        )

    return FontAsset(
        source=source,
        source_name=source_name,
        symbol=_symbol(value, source_name, "font", label, str(size)),
        size=size,
        bpp=bpp,
        ranges=ranges,
        symbols=symbols,
        args=args,
    )


def load_manifest(path: Path) -> AssetManifest:
    path = path.resolve()
    try:
        content = json.loads(path.read_text(encoding="utf-8"))
    except FileNotFoundError as exc:
        raise AssetError(f"manifest does not exist: {path}") from exc
    except json.JSONDecodeError as exc:
        raise AssetError(f"invalid JSON in {path}: {exc}") from exc

    root = path.parent
    value = _expect_object(content, "manifest")
    _reject_unknown_keys(value, {"fonts", "images", "version"}, "manifest")
    version = value.get("version")
    if isinstance(version, bool) or not isinstance(version, int) or version != 1:
        raise AssetError("manifest.version must be 1")

    images = tuple(
        _parse_image(root, item, index)
        for index, item in enumerate(_expect_list(value.get("images", []), "images"))
    )
    fonts = tuple(
        _parse_font(root, item, index)
        for index, item in enumerate(_expect_list(value.get("fonts", []), "fonts"))
    )

    used_symbols: dict[str, str] = {}
    for asset in (*images, *fonts):
        if asset.symbol in used_symbols:
            raise AssetError(
                f"symbol collision: {used_symbols[asset.symbol]} and "
                f"{asset.source_name} both use {asset.symbol}"
            )
        used_symbols[asset.symbol] = asset.source_name

    return AssetManifest(
        root=root,
        images=tuple(sorted(images, key=lambda item: item.symbol)),
        fonts=tuple(sorted(fonts, key=lambda item: item.symbol)),
    )


def _find_lvgl_image_script(root: Path, explicit: Optional[Path]) -> Path:
    candidates = []
    if explicit is not None:
        candidates.append(explicit.expanduser())
    configured = os.environ.get("LVGL_IMAGE_CONVERTER")
    if configured:
        candidates.append(Path(configured).expanduser())

    for parent in (root, *root.parents):
        candidates.extend(
            [
                parent / "dependencies/lvgl/scripts/LVGLImage.py",
                parent / "components/lvgl/scripts/LVGLImage.py",
                parent / "managed_components/lvgl__lvgl/scripts/LVGLImage.py",
            ]
        )

    for candidate in candidates:
        candidate = candidate.resolve()
        if candidate.is_file():
            return candidate
    raise AssetError(
        "cannot find LVGLImage.py; fetch project dependencies or pass --lvgl-image. "
        "LVGL_IMAGE_CONVERTER may also point to the script"
    )


def _load_lvgl_image_module(script: Path):
    spec = importlib.util.spec_from_file_location("chain_captain_lvgl_image", script)
    if spec is None or spec.loader is None:
        raise AssetError(f"cannot load LVGL image converter: {script}")
    module = importlib.util.module_from_spec(spec)
    try:
        spec.loader.exec_module(module)
    except ImportError as exc:
        raise AssetError(
            f"cannot load {script}: {exc}. Install assets/requirements.txt "
            "in the Python environment used for generation"
        ) from exc
    return module


def _flatten_rgba(r: int, g: int, b: int, a: int, background: int) -> tuple[int, int, int, int]:
    bb = background & 0xFF
    bg = (background >> 8) & 0xFF
    br = (background >> 16) & 0xFF

    return (
        (r * a + br * (255 - a)) // 255,
        (g * a + bg * (255 - a)) // 255,
        (b * a + bb * (255 - a)) // 255,
        a,
    )


def _rasterize_svg(asset: ImageAsset, output: Path) -> None:
    try:
        import cairosvg
    except ImportError as exc:
        raise AssetError(
            "SVG conversion requires CairoSVG; install assets/requirements.txt before generating resources"
        ) from exc

    try:
        cairosvg.svg2png(
            url=str(asset.source),
            write_to=str(output),
            output_width=asset.width,
            output_height=asset.height,
        )
    except Exception as exc:
        raise AssetError(f"failed to rasterize {asset.source_name}: {exc}") from exc


def _prepare_raster_image(asset: ImageAsset, temp_dir: Path) -> Path:
    extension = asset.source.suffix.lower()
    if extension == ".svg":
        output = temp_dir / f"{asset.symbol}.png"
        _rasterize_svg(asset, output)
        return output

    if extension == ".png" and asset.width is None:
        return asset.source

    try:
        from PIL import Image
    except ImportError as exc:
        raise AssetError(
            "JPEG conversion and raster image resizing require Pillow; install assets/requirements.txt"
        ) from exc

    output = temp_dir / f"{asset.symbol}.png"
    with Image.open(asset.source) as image:
        if asset.width is not None and asset.height is not None:
            image = image.resize((asset.width, asset.height), Image.Resampling.LANCZOS)
        image = image.convert("RGBA" if asset.format in LVGL_ALPHA_FORMATS else "RGB")
        image.save(output)
    return output


def _generate_lvgl_image(asset: ImageAsset, module: Any, temp_dir: Path) -> str:
    input_path = _prepare_raster_image(asset, temp_dir)
    try:
        color_format = module.ColorFormat[asset.format.removeprefix("LVGL_")]
    except KeyError as exc:
        raise AssetError(f"LVGL converter does not support {asset.format}") from exc

    output = temp_dir / f"{asset.symbol}.c"
    try:
        image = module.LVGLImage().from_png(str(input_path), color_format)
        image.adjust_stride(align=asset.stride_align)
        image.to_c_array(str(output), outputname=asset.symbol)
    except Exception as exc:
        raise AssetError(f"failed to convert {asset.source_name}: {exc}") from exc
    content = output.read_text(encoding="utf-8").rstrip()
    return f"{IMAGE_MARKER}\n{content}\n"


def _rgb565(r: int, g: int, b: int) -> int:
    return ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)


def _swap_u16(value: int) -> int:
    return ((value & 0xFF) << 8) | (value >> 8)


def _generate_gfx_image(asset: ImageAsset, temp_dir: Path) -> str:
    if asset.format != "GFX_RGB565_SWAPPED":
        raise AssetError(f"GFX converter does not support {asset.format}")

    try:
        from PIL import Image
    except ImportError as exc:
        raise AssetError(
            "GFX image conversion requires Pillow; install assets/requirements.txt"
        ) from exc

    input_path = _prepare_raster_image(asset, temp_dir)
    try:
        with Image.open(input_path) as source:
            image = source.convert("RGB")
            width, height = image.size
            pixels = [_swap_u16(_rgb565(r, g, b)) for r, g, b in image.get_flattened_data()]
    except Exception as exc:
        raise AssetError(f"failed to convert {asset.source_name}: {exc}") from exc

    values_per_line = 12
    data_lines = [
        "    " + ", ".join(f"0x{value:04x}" for value in pixels[offset : offset + values_per_line]) + ","
        for offset in range(0, len(pixels), values_per_line)
    ]
    data = "\n".join(data_lines)
    return (
        f"{IMAGE_MARKER}\n"
        '#include "../gfx_image.h"\n\n'
        f"static const uint16_t {asset.symbol}_map[] = {{\n{data}\n}};\n\n"
        f"const gfx_image_dsc_t {asset.symbol} = {{\n"
        f"    .data = {asset.symbol}_map,\n"
        f"    .data_size = sizeof({asset.symbol}_map),\n"
        f"    .width = {width},\n"
        f"    .height = {height},\n"
        f"    .stride = {width * 2},\n"
        "    .format = GFX_IMAGE_FORMAT_RGB565_SWAPPED,\n"
        "};\n"
    )


def _font_converter(explicit: Optional[Path]) -> str:
    if explicit is not None:
        candidate = str(explicit.expanduser())
    else:
        candidate = os.environ.get("LV_FONT_CONV", "") or shutil.which("lv_font_conv") or ""
    if not candidate or not Path(candidate).is_file():
        raise AssetError(
            "cannot find lv_font_conv; install it and add it to PATH, pass --font-converter, "
            "or set LV_FONT_CONV"
        )
    return candidate


def _generate_font(asset: FontAsset, converter: str, temp_dir: Path) -> str:
    output = temp_dir / f"{asset.symbol}.c"
    command = [
        converter,
        *asset.args,
        "--size",
        str(asset.size),
        "--bpp",
        str(asset.bpp),
        "--font",
        str(asset.source),
    ]
    for font_range in asset.ranges:
        command.extend(["-r", font_range])
    if asset.symbols:
        command.extend(["--symbols", asset.symbols])
    command.extend(["--format", "lvgl", "-o", str(output)])

    try:
        subprocess.run(command, check=True)
    except (OSError, subprocess.CalledProcessError) as exc:
        raise AssetError(f"failed to convert {asset.source_name}: {exc}") from exc

    content = output.read_text(encoding="utf-8")
    content = content.replace(str(output), f"res_c/{output.name}")
    content = content.replace(str(asset.source), asset.source_name)
    if "--no-compress" in asset.args:
        subpixel_initializer = (
            "#if !(LVGL_VERSION_MAJOR == 6 && LVGL_VERSION_MINOR == 0)\n"
            "    .subpx = LV_FONT_SUBPX_NONE,\n"
            "#endif\n"
        )
        if content.count(subpixel_initializer) != 1:
            raise AssetError(f"cannot mark {asset.symbol} as a static bitmap font")
        static_bitmap_initializer = (
            "#if LVGL_VERSION_MAJOR >= 9\n"
            "    .static_bitmap = 1,\n"
            "#endif\n"
        )
        content = content.replace(
            subpixel_initializer,
            subpixel_initializer + static_bitmap_initializer,
        )
    return f"{FONT_MARKER}\n{content.rstrip()}\n"


def _header_content(images: Iterable[ImageAsset], fonts: Iterable[FontAsset]) -> str:
    images = list(images)
    fonts = list(fonts)
    gfx_images = [asset for asset in images if asset.format.startswith("GFX_")]
    lvgl_images = [asset for asset in images if asset.format.startswith("LVGL_")]
    lines = [
        "#pragma once",
        "",
        HEADER_MARKER,
        "",
        "#if defined(LV_LVGL_H_INCLUDE_SIMPLE)",
        '#include "lvgl.h"',
        "#elif defined(LV_LVGL_H_INCLUDE_SYSTEM)",
        "#include <lvgl.h>",
        "#else",
        '#include "lvgl/lvgl.h"',
        "#endif",
        "",
    ]
    if gfx_images:
        lines.extend(['#include "gfx_image.h"', ""])
    lines.extend(
        [
            "#ifdef __cplusplus",
            'extern "C" {',
            "#endif",
            "",
            "/* GFX images */" if gfx_images else "/* GFX images: none */",
        ]
    )
    lines.extend(f"extern const gfx_image_dsc_t {asset.symbol};" for asset in gfx_images)
    lines.extend(["", "/* LVGL images */" if lvgl_images else "/* LVGL images: none */"])
    lines.extend(f"LV_IMAGE_DECLARE({asset.symbol});" for asset in lvgl_images)
    lines.extend(["", "/* Fonts */" if fonts else "/* Fonts: none */"])
    lines.extend(f"LV_FONT_DECLARE({asset.symbol});" for asset in fonts)
    lines.extend(["", "#ifdef __cplusplus", "}", "#endif", ""])
    return "\n".join(lines)


def _cmake_content(root: Path, sources: Iterable[Path]) -> str:
    lines = [CMAKE_MARKER, "", "set(CHAIN_CAPTAIN_ASSET_SOURCES"]
    for source in sorted(sources):
        relative = source.resolve().relative_to(root.resolve()).as_posix()
        lines.append(f'    "${{CMAKE_CURRENT_LIST_DIR}}/{relative}"')
    lines.extend([")", ""])
    return "\n".join(lines)


def _first_line(path: Path) -> str:
    try:
        return path.read_text(encoding="utf-8", errors="ignore").splitlines()[0]
    except (FileNotFoundError, IndexError):
        return ""


def _stale_outputs(output_dir: Path, expected: set[Path]) -> list[Path]:
    if not output_dir.exists():
        return []
    return sorted(
        path
        for path in output_dir.glob("*.c")
        if path.resolve() not in expected and _first_line(path) in GENERATED_MARKERS
    )


def _atomic_write(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    handle = tempfile.NamedTemporaryFile(mode="w", encoding="utf-8", dir=path.parent, delete=False)
    temporary = Path(handle.name)
    try:
        with handle:
            handle.write(content)
        os.replace(temporary, path)
    finally:
        temporary.unlink(missing_ok=True)


def _synchronize(outputs: dict[Path, str], output_dir: Path, check: bool) -> bool:
    expected = {path.resolve() for path in outputs if path.suffix == ".c"}
    stale = _stale_outputs(output_dir, expected)
    outdated = [
        path
        for path, content in outputs.items()
        if not path.exists() or path.read_text(encoding="utf-8") != content
    ]

    if check:
        for path in outdated:
            print(f"outdated {path}")
        for path in stale:
            print(f"stale {path}")
        if outdated or stale:
            return False
        print("assets are up to date")
        return True

    for path in outdated:
        _atomic_write(path, outputs[path])
        print(f"updated {path}")
    for path in stale:
        path.unlink()
        print(f"removed stale {path}")
    if not outdated and not stale:
        print("assets are up to date")
    return True


def generate_assets(
    manifest_path: Path,
    output_dir: Path,
    header_path: Path,
    cmake_path: Path,
    check: bool = False,
    lvgl_image_script: Optional[Path] = None,
    font_converter: Optional[Path] = None,
) -> bool:
    manifest = load_manifest(manifest_path)
    output_dir = output_dir.resolve()
    header_path = header_path.resolve()
    cmake_path = cmake_path.resolve()

    outputs: dict[Path, str] = {}
    generated_sources = []
    with tempfile.TemporaryDirectory(prefix="chain-captain-assets-") as temporary:
        temp_dir = Path(temporary)
        lvgl_images = [asset for asset in manifest.images if asset.format.startswith("LVGL_")]
        if lvgl_images:
            script = _find_lvgl_image_script(manifest.root, lvgl_image_script)
            module = _load_lvgl_image_module(script)
            # LVGLImage.py divides alpha flattening by 256, darkening even fully opaque pixels.
            if hasattr(module, "color_pre_multiply"):
                module.color_pre_multiply = _flatten_rgba
        else:
            module = None

        for asset in manifest.images:
            output = output_dir / f"{asset.symbol}.c"
            if asset.format.startswith("GFX_"):
                outputs[output] = _generate_gfx_image(asset, temp_dir)
            else:
                outputs[output] = _generate_lvgl_image(asset, module, temp_dir)
            generated_sources.append(output)

        if manifest.fonts:
            converter = _font_converter(font_converter)
            for asset in manifest.fonts:
                output = output_dir / f"{asset.symbol}.c"
                outputs[output] = _generate_font(asset, converter, temp_dir)
                generated_sources.append(output)

    outputs[header_path] = _header_content(manifest.images, manifest.fonts)
    outputs[cmake_path] = _cmake_content(manifest.root, generated_sources)
    return _synchronize(outputs, output_dir, check)


def _parse_args() -> argparse.Namespace:
    asset_dir = Path(__file__).resolve().parent
    parser = argparse.ArgumentParser(description="Generate Chain Captain assets from manifest.json")
    parser.add_argument("--manifest", type=Path, default=asset_dir / "manifest.json")
    parser.add_argument("--output-dir", type=Path)
    parser.add_argument("--header", type=Path)
    parser.add_argument("--cmake", type=Path)
    parser.add_argument("--lvgl-image", type=Path, help="Path to LVGLImage.py")
    parser.add_argument("--font-converter", type=Path, help="Path to lv_font_conv")
    parser.add_argument("--check", action="store_true", help="Fail if generated files differ without changing them")
    return parser.parse_args()


def main() -> int:
    args = _parse_args()
    manifest_path = args.manifest.resolve()
    root = manifest_path.parent
    try:
        current = generate_assets(
            manifest_path=manifest_path,
            output_dir=args.output_dir or root / "res_c",
            header_path=args.header or root / "assets.h",
            cmake_path=args.cmake or root / "assets.cmake",
            check=args.check,
            lvgl_image_script=args.lvgl_image,
            font_converter=args.font_converter,
        )
    except AssetError as exc:
        print(f"asset error: {exc}")
        return 2
    return 0 if current else 1


if __name__ == "__main__":
    raise SystemExit(main())
